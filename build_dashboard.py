#!/usr/bin/env python3
"""Rebuild firmware/ACL_Guard/dashboard.h from dashboard/index.html.

Usage:  python build_dashboard.py
Then upload ACL_Guard.ino again with the Arduino IDE.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "dashboard" / "index.html"
OUT = ROOT / "firmware" / "ACL_Guard" / "dashboard.h"
DELIM = "ACLHTML"


def main() -> int:
    html = SRC.read_text(encoding="utf-8")
    if f"){DELIM}\"" in html:
        print(f"error: index.html contains ')%s\"', which would end the C++ string" % DELIM)
        return 1

    header = (
        "// AUTO-GENERATED from dashboard/index.html by build_dashboard.py\n"
        "// Do not edit this file. Edit index.html, then run: python build_dashboard.py\n"
        "#pragma once\n"
        "#include <pgmspace.h>\n\n"
        f'const char DASHBOARD_HTML[] PROGMEM = R"{DELIM}(' + html + f'){DELIM}";\n'
    )
    OUT.write_text(header, encoding="utf-8", newline="\n")
    size = len(html.encode("utf-8"))
    print(f"Wrote {OUT.relative_to(ROOT)} ({size / 1024:.1f} KB of HTML)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
